print(4 & 5) #binary 100 and 101 = 100  -> bitwise conjunction
print(4 | 5) #binary 100 or 101 = 101  -> bitwise disjunction
print(~13) #not operator (2s compliment) -> bitwise negation
print(10 ^ 13) #xor 1010 xor 1101 = 0111 -> bitwise exclusive
#Left shift
print(5 << 2)
#Right shift
print(5 >> 2)